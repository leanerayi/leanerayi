p('第二，推进社会认同理论与JD-R模型的情境化整合。社会认同理论解释职业价值、群体归属和岗位认可如何形成身份资源；JD-R模型解释工作要求和工作资源如何影响耗竭。本文以工作满意度作为连接变量，把身份认同与组织制度评价放入同一分析框架。')
p('第三，深化工作满意度中介机制研究。相比仅讨论职业认同与职业倦怠的相关关系，本文进一步分析职业认同是否通过改善员工对薪酬绩效、发展机会、组织支持、工作条件和协同环境的综合评价而降低职业倦怠，从而更完整地解释其作用路径。')

