h3('1.1.1 研究背景')
p('公立医院是我国公共医疗服务体系的重要主体，其治理能力不仅影响医疗质量和医院运行效率，也关系医保基金使用效率和群众就医获得感。近年来，我国公立医院发展理念逐步由规模扩张转向提质增效，由经验管理转向精细化、绩效化和数据驱动治理[1-4]。在这一过程中，病案数据从临床记录资料进一步转化为医疗质量评价、医院绩效监测、专科评价、医保支付和运营决策的重要治理资源。DRG/DIP支付改革进一步提高了主要诊断、其他诊断、手术操作、资源消耗及首页数据质量的重要性[5-6]。')
p('病案管理人员的岗位功能由传统归档保管明显扩展。除病案收集、整理和利用外，越来越多岗位承担疾病分类编码、病案首页质控、数据统计、医保支付支持、异常病例反馈和跨部门沟通等任务。岗位专业性、责任风险和数据治理属性持续增强，但组织中的岗位声誉、绩效评价、人员配置和职业发展机制并不一定同步调整。由此形成的“责任增加—资源补充不足”“岗位重要性上升—组织认可不足”等结构性张力，是研究职业认同、工作满意度和职业倦怠的重要公共管理背景。')
p('既有医疗卫生人力资源研究表明，工作负荷、资源配置、管理支持、职业发展和绩效公平与员工职业状态密切相关。例如，国内三级公立医院满意度研究显示，薪酬与工作量匹配、发展机会和组织管理仍是较突出的改进领域[24]；妇幼健康从业医生研究表明，职业发展、社会支持、绩效考核满意度和薪酬满意度均与职业认同相关。国际研究也发现，工作过载与医疗机构工作人员职业倦怠和离职意向显著相关，且非临床工作人员同样受到影响[56]。')
p('职业倦怠不应被简单理解为个体抗压能力不足。世界卫生组织将其界定为工作情境中的职业现象[67]；JD-R模型进一步指出，高工作要求会持续消耗个体资源，而工作资源能够帮助完成任务、促进成长并缓冲耗竭[68-70]。对于病案管理人员而言，病例量、编码准确性责任、上报时限、政策规则变化和跨部门协调属于典型工作要求；人员配置、领导支持、培训、职业发展、绩效回报和信息系统支持则构成关键工作资源。')
p('与本研究最接近的洪梦园基层卫生人员研究以972名调查对象为样本，发现职业认同总体得分M（P25，P75）为49.00（44.00，55.00），工作满意度为40.66±9.03，职业倦怠阳性检出率为58.2%；SEM结果显示职业认同正向预测工作满意度，职业认同和工作满意度均负向预测职业倦怠，工作满意度的中介效应占总效应30.23%。该结果为三变量关系提供了重要经验参照，但研究对象为基层卫生人员，无法直接替代病案管理人员的实证证据。本文因此将上述作用关系置于公立医院非临床数据治理岗位情境中重新检验。')

