p('本节按照公共管理学术论文的综述逻辑，在分别梳理职业认同、工作满意度和职业倦怠的概念演进、国内外研究现状及影响因素的基础上，进一步评述三者之间的两两关系和中介机制。综述不仅关注个体心理变量，还重点考察组织支持、领导行为、绩效制度、职业发展、工作负荷、行政负担、协同机制和信息化等公共组织治理因素。')

h3('1.2.1 职业认同：概念演进、研究现状与影响因素')
p('职业认同源于身份认同与社会认同研究。社会认同理论认为，个体通过社会分类将自身纳入特定群体，并通过群体比较获得价值感、归属感和行为规范[68-70]。进入组织研究后，职业身份逐步被视为影响员工工作态度和行为的重要身份基础。职业认同因而不仅表示“是否喜欢某一职业”，还包括对职业价值、角色规范、专业共同体、社会声誉和职业发展前景的综合认可。')
p('国外研究起步较早，早期重点关注教师、护士及其他专业群体的身份形成，近年则更加关注职业认同与卫生人力资源稳定、工作满意度、职业倦怠和离职意向之间的关系。Zhang等将职业认同、工作满意度、职业倦怠和离职意向纳入同一模型，发现职业认同较高的乡村公共卫生服务人员通常具有更高工作满意度、更低倦怠和更低离职意向[53]。Zhong等针对新入职护士的研究同样指出，职业认同与工作满意度均是解释职业稳定的重要变量[54]；Qu等研究发现，职业倦怠在职业认同影响全科医生离职意向过程中具有中介作用[55]。这些研究提示，职业认同既是一种职业身份变量，也是一种能够影响后续工作体验与职业健康的心理资源。')
p('国外研究对职业认同影响因素的解释逐步从个体特征转向组织情境。专业社会化、工作胜任力和职业经历构成个体层面的重要因素；组织支持、领导行为、职业自主性、培训与发展机会、绩效反馈和公平感则构成组织层面的关键因素。特别是在公共医疗服务中，员工能否将个人职业价值与组织使命联系起来，会影响职业身份的稳定程度。因此，职业认同具有明显的组织治理属性，而非单纯的个人偏好。')
p('国内卫生领域职业认同研究起步较晚，但近年来发展较快。相关研究对象由护士和医生逐渐扩展到全科医生、院前急救人员、基层卫生人员和医院工作人员。冯星淼等发现，院前急救医护人员职业认同与组织环境均会影响职业倦怠[23]；公立医院价值医疗服务动机研究则将专业认同进一步与公共服务价值、医院使命和服务行为联系起来[9]。这类研究表明，在公立医院情境中，职业认同具有专业身份认同与公共价值认同双重属性。')
p('影响国内医务人员职业认同的因素大致可归为四类：一是人口与职业经历因素，如年龄、工龄、职称和专业能力；二是物质与制度因素，如薪酬、绩效考核、公平感和晋升机会；三是组织关系因素，如领导支持、同事支持、组织环境和团队协同；四是社会价值因素，如社会声誉、职业尊重和公共服务意义。值得注意的是，“高认同但低承诺”等研究发现说明，员工即使认可职业价值，如果组织无法提供合理回报、发展机会和资源支持，也可能难以形成稳定的组织承诺[19]。这为本文把工作满意度设置为中介变量提供了理论依据。')
p('针对病案管理人员的职业认同直接研究仍然稀缺。现有病案管理研究更多关注队伍结构、专业能力、病案首页质量和DRG/DIP管理[46-48]。然而，病案管理岗位具有成果隐性、责任显性和高度协同的特点：工作人员对岗位公共价值的认识、医院是否认可其数据治理贡献、职业发展是否清晰，均可能影响其职业认同。由此，病案管理人员职业认同具有较强的组织制度依赖性。')

h3('1.2.2 工作满意度：概念演进、研究现状与影响因素')
p('工作满意度是员工对工作内容、回报、管理、发展、关系和环境进行综合评价后形成的态度与情感体验。经典研究既强调对工作整体的情感评价，也强调实际获得与个人期望之间的差距。医院情境中的工作满意度通常包含薪酬福利、工作负荷、职业发展、领导管理、同事关系、工作环境和绩效制度等维度[52]。从公共管理视角看，工作满意度既是员工主观体验，也是公共组织人力资源制度质量的结果变量。')
p('国外医疗卫生人员工作满意度研究较为成熟，重点从工作条件、薪酬、职业自主、管理支持和工作—生活平衡等方面解释差异。Anand等对医疗官员的研究发现，适宜工作时间有助于形成满意感，而薪酬与工作压力不匹配是重要不满来源[71]。Lopes等采用结构方程模型发现，工作满意度与职业倦怠、抑郁症状以及患者安全文化之间存在显著联系[72]。这说明满意度不仅是个人福利指标，还可能通过工作投入、沟通和规范执行关联组织绩效。')
p('近年的国际研究更加突出满意度的组织来源。Rotenstein等对医疗机构工作人员的研究指出，工作过载与倦怠和离职意向显著相关[56]；Aiken等发现，人员配置、工作环境和管理信任与医务人员职业体验、流动意愿及患者安全密切相关[57]；Shanafelt等对医生群体的连续调查也显示，倦怠增加往往伴随工作—生活融合满意度下降[61]。这些成果表明，满意度是工作要求与资源配置结果的主观反映。')
p('国内医务人员满意度研究已由一般现状调查逐步转向制度因素和治理机制分析。李熹阳等对三级公立医院医务人员的调查显示，不同满意度维度差异明显，薪酬与工作量匹配、职业发展和组织管理仍是需要重点改进的方面[24]。医院薪酬政策和绩效改革研究进一步指出，公立医院薪酬制度需要在公益目标、岗位价值和激励约束之间取得平衡，简单以业务数量为核心的分配模式容易造成不同岗位之间的价值失衡[14-15]。')
p('国内满意度影响因素可以归纳为工作本身、组织制度和个体条件三层。工作本身包括工作量、任务复杂度、角色冲突和工作意义；组织制度包括薪酬绩效、晋升发展、组织支持、管理公平和信息化流程；个体因素包括年龄、工龄、岗位类别和胜任力。对于病案管理人员而言，工作满意度还受到数据质量责任、DRG/DIP新增任务、跨部门协作和信息系统重复操作等特定因素影响。韩慧欣等对病案管理人员的研究指出，工作强度、职业发展和职业价值认同是影响满意度的重要因素[76]；陈建伟等和王艳华等的研究也显示，加班、压力、聘用形式、岗位条件及职业倦怠与满意度密切相关[77-78]。')
p('因此，病案管理人员工作满意度应被视为对岗位要求、组织资源和制度回报是否匹配的综合评价，而不仅是对工资或工作环境的单项评价。本文将其设置为职业认同影响职业倦怠的中介变量，正是基于职业身份需要通过现实组织体验转化为具体职业健康结果这一逻辑。')

h3('1.2.3 职业倦怠：概念演进、研究现状与影响因素')
p('职业倦怠研究经历了从现象描述到结构测量，再到组织机制解释的发展过程。Maslach等提出的三维结构将职业倦怠概括为情绪耗竭、去人格化或工作疏离以及个人成就感降低。世界卫生组织在ICD-11中将其界定为工作情境中的职业现象[67]。此后，研究重点逐渐从“谁更容易倦怠”转向“什么样的工作环境会持续产生倦怠”。')
p('JD-R模型是解释职业倦怠的重要组织理论。模型指出，工作要求会消耗个体资源并启动健康损耗过程，工作资源则能够帮助完成任务、降低成本、促进成长并激活动机过程。对于医疗组织而言，工作过载、人员不足、时间压力、情绪劳动、行政负担和信息记录负担均可能构成工作要求；自主权、组织支持、领导支持、培训、发展机会和信息系统支持则属于工作资源。')
p('国外医疗卫生职业倦怠研究已形成大量实证证据。Rotenstein等发现，工作过载与医疗工作者倦怠和离职意向显著相关，而且非临床工作人员同样受到影响[56]。Li等系统综述显示，护士倦怠与较低服务质量、患者安全和患者满意度相关[58]；Quesada-Puga等的Meta分析进一步确认工作满意度与职业倦怠之间存在稳定负向联系[59]。Gesner等指出，文书记录和电子记录负担可能成为新的耗竭来源[62]。这些研究共同推动职业倦怠干预从个体心理调适转向工作场所和组织制度改善[60,66]。')
p('国内职业倦怠研究也逐步从个体因素解释转向公共组织治理解释。基层卫生技术人员扎根研究发现，工作任务、职业发展、组织支持和公共服务环境共同作用于职业倦怠[18]；行政负担研究进一步强调报表任务、政策执行要求和组织资源之间的失衡会增加耗竭[20]。三级公立医院医务人员职业倦怠文献分析也表明，职业倦怠在不同岗位中普遍存在，并受到工作量、组织支持、绩效制度和发展资源影响[32]。')
p('病案管理人员职业倦怠研究目前仍相对薄弱。早期研究已指出人员配置不足、工作环境、培训机会、激励机制和职业发展等因素可能与倦怠相关[47-48]，但较多研究属于经验总结，缺少基于成熟量表的大样本机制检验。当前病案管理人员还需要面对编码规则持续更新、医保支付改革、病案首页质控、数据上报和信息系统操作等新增工作要求，过去研究难以充分解释新制度环境下的倦怠机制。')
p('从影响因素看，病案管理人员职业倦怠至少涉及四个层次：个体层面的专业能力和职业预期；岗位层面的工作量、时限和责任风险；组织层面的人员配置、绩效公平、领导支持和职业发展；制度技术层面的DRG/DIP要求、数据报送、跨部门权责以及信息系统负担。由此，职业倦怠本质上是多层治理因素共同作用的结果。')

h3('1.2.4 职业认同、工作满意度与职业倦怠关系研究')
p('职业认同与工作满意度总体表现为正向关系。职业认同能够增强员工对工作意义、职业角色和专业价值的积极评价，从而提高对工作本身的满意感。Zhang等、Zhong等的研究均显示，职业认同与工作满意度显著相关[53-54]。国内基层卫生人员和医疗人员研究也得到类似结论。其内在逻辑在于：当员工能够把职业活动与个人价值及公共服务使命相联系时，更容易从工作中获得意义感和成就感；但这种认同能否持续转化为满意度，还依赖组织是否提供公平回报、发展机会和支持资源。')
p('职业认同与职业倦怠通常呈负向关系。职业认同能够提供意义感、角色清晰度和职业归属，是应对高要求环境的重要身份资源。Qu等发现，职业倦怠在职业认同影响全科医生离职意向的过程中发挥重要作用[55]。国内院前急救人员及医院行政人员研究同样显示，职业认同下降往往伴随职业倦怠上升[23,79]。但值得注意的是，高职业认同并不必然意味着低倦怠：如果高认同员工长期承担超额职责却得不到相应组织资源，强责任感也可能转化为更高资源消耗。')
p('工作满意度与职业倦怠之间的负向关系得到较多一致证据。Quesada-Puga等Meta分析显示，满意度下降通常伴随情绪耗竭和工作疏离升高[59]；Lopes等的SEM研究也发现满意度、倦怠、抑郁症状与安全文化相互关联[72]。国内研究同样发现，工作满意度与职业倦怠显著相关，工作压力、薪酬公平、心理弹性和组织支持会通过满意度或倦怠影响组织行为[28-31,73-75,80]。')
p('关于工作满意度的中介作用，近年研究开始把三变量放入连续路径。洪梦园对972名基层卫生人员的研究显示，职业认同正向预测工作满意度、负向预测职业倦怠，工作满意度负向预测职业倦怠；工作满意度中介效应为-0.120，占总效应30.23%。这一结果说明职业认同并不只是直接作用于倦怠，而可能先改变员工对薪酬、环境、发展和管理条件的综合评价，再影响耗竭程度。该研究为本文模型提供了直接参照，但病案管理人员的工作任务结构、组织位置和数据治理责任不同，仍需单独检验。')

h3('1.2.5 病案管理人员相关研究')
p('在DRG/DIP改革、三级公立医院绩效监测和智慧医院建设背景下，病案管理人员正由传统病案保管者转向医疗数据治理参与者。病案首页数据已成为医疗质量评价、医保支付、运营管理和绩效监测的重要基础。岗位转型提高了疾病编码、医学知识、数据分析和跨部门协调能力要求，也增加了责任风险和认知负荷。')
p('现有病案管理人员研究主要集中于队伍建设、工作满意度、职业倦怠和管理模式。王东华等对病案管理人员现状的调查提示，人员专业结构和岗位配置仍有改善空间[46]。韩慧欣等对河南省病案管理人员的研究发现，工作强度、职业发展和职业价值认同是满意度的重要影响因素[76]；陈建伟等和王艳华等进一步将加班、压力、聘用形式、应对方式和倦怠纳入满意度解释[77-78]。职业倦怠方面，既有研究将人员配置不足、培训机会少、发展空间有限和激励不足等列为主要原因[47-48]。')
p('然而，病案管理人员研究仍存在明显局限：一是研究对象多集中于单一医院或地区，外部效度有限；二是大量研究停留在现状描述和影响因素罗列，缺少完整理论模型；三是较少将岗位公共价值、组织认可、绩效制度和跨部门协同纳入同一分析框架；四是尚缺乏职业认同—工作满意度—职业倦怠的中介机制研究。本文正是在这一缺口上展开。')

h2('1.3 研究述评')
p('综合国内外研究，职业认同、工作满意度和职业倦怠已经形成较为丰富的理论和实证积累，但从公共管理视角看仍有进一步拓展空间。')
p('第一，研究对象存在结构性缺口。现有卫生领域成果高度集中于医生、护士、全科医生和基层卫生人员，对病案管理、卫生信息、医保数据等非临床专业技术人员关注不足。病案管理人员既是专业技术人员，又是医院数据治理和政策执行的支撑主体，其职业状态具有独特制度情境。')
p('第二，研究内容仍较分散。大量研究分别考察职业认同、工作满意度或职业倦怠与离职意向、工作投入的关系，直接检验“职业认同—工作满意度—职业倦怠”完整机制的成果较少。')
p('第三，公共管理解释仍不足。部分研究倾向于把职业倦怠归因于人格、韧性或个体压力，而对岗位价值、人员配置、绩效制度、行政负担、职业发展、跨部门协同和信息系统等组织治理因素关注不足。')
p('第四，研究方法仍可深化。横断面问卷和单因素、相关分析较多，利用SEM与Bootstrap检验机制并辅以访谈解释制度成因的研究相对有限。本文将量化路径检验与质性访谈相结合，以提高机制解释力。')
p('因此，本文以B市公立医院病案管理人员为研究对象，在社会认同理论和JD-R模型基础上，将职业认同设置为自变量、工作满意度设置为中介变量、职业倦怠设置为因变量，并将岗位价值、绩效制度、职业发展、组织支持、人员配置、协同治理和信息系统作为访谈重点，从而形成兼顾个体职业态度与公共组织治理环境的分析框架。')

