h1('第二章 概念界定与理论基础')
h2('2.1 公立医院')
p('本文所称公立医院，是指由政府举办、承担基本医疗服务、医疗质量保障和公共卫生相关职责，具有公益属性的医疗机构。公立医院既是专业医疗组织，也是公共服务组织，其人力资源制度、绩效管理和内部治理具有明显公共管理属性。')
h2('2.2 病案管理人员')
p('本文所称病案管理人员，是指B市公立医院中长期从事病案收集、整理、归档、疾病与手术操作编码、病案首页质量控制、统计分析、数据上报、病案信息服务以及DRG/DIP相关数据支持工作的人员。')
h2('2.3 职业认同')
p('职业认同是个体对自身职业角色、专业价值、群体归属、组织贡献和职业发展形成的综合认知、情感依附与持续从业倾向。结合病案岗位，本文重点关注职业价值认同、岗位角色认同、专业认可、组织认可和发展信心。')
h2('2.4 工作满意度')
p('工作满意度是病案管理人员对工作内容、薪酬绩效、职业发展、领导与组织支持、工作环境、信息系统和跨部门协作等工作条件进行评价后形成的总体态度。')
h2('2.5 职业倦怠')
p('职业倦怠是长期工作压力未得到有效管理后形成的职业状态，主要表现为情绪耗竭、工作疏离或冷漠以及职业效能和成就感下降。本文限定其发生于病案管理工作情境，不等同于一般生活疲劳。')
h2('2.6 社会认同理论')
p('社会认同理论认为，个体通过所属群体形成自我分类，并通过群体比较获得价值感、归属感和行为规范[68-70]。当病案管理人员能够认同自身职业群体的专业价值和公共贡献，并感受到组织认可时，更容易形成积极职业身份；反之，岗位长期边缘化、专业贡献缺少认可可能削弱身份价值。')
h2('2.7 工作要求—资源模型')
p('JD-R模型将工作特征区分为工作要求与工作资源。病案数量、编码准确性责任、时限、政策规则变化、反复退回和跨部门沟通属于工作要求；人员配置、培训、领导支持、绩效回报、职业发展、同事协作和信息系统支持属于工作资源。高要求且资源不足会推动耗竭过程，资源充分则有助于激活动机并缓冲压力。')
h2('2.8 理论整合')
p('社会认同理论主要回答“职业价值和群体归属为何影响工作态度”，JD-R模型主要回答“工作要求与资源为何产生或缓冲职业倦怠”。将两者结合，可形成“身份资源—工作评价—健康损耗”的逻辑：职业认同提供意义与归属资源，工作满意度反映员工对要求、资源和回报关系的综合评价，职业倦怠则是长期失衡的结果。')
